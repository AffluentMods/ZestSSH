"""Generate lib/core/data/host_icon_svgs.dart from tool/host_icons/svg/.

The host-card icon set: 130 generic line icons (24x24, 1.75 stroke,
currentColor; the C2PA manifest each shipped with is stripped here) plus the
OS / brand marks built from Simple Icons (CC0 SVG data, 24x24 with a 2px inset
so filled logos weigh the same as the strokes). Every icon is tinted at render
time, so the files carry no colour of their own.

Inputs (checked in, so the set can be regenerated without the originals):
  tool/host_icons/svg/line/<name>.svg     the generic icons
  tool/host_icons/svg/brand/<id>.svg      the brand marks
  tool/host_icons/line-index.json         name -> category for the line icons

Run:  python tool/host_icons/gen_host_icons.py
"""
import io
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "lib", "core", "data", "host_icon_svgs.dart")

META = re.compile(r"<metadata>.*?</metadata>", re.S)
C2PA_NS = re.compile(r'\s*xmlns:c2pa="[^"]*"')
WS = re.compile(r">\s+<")
# Line breaks inside a tag (hand-written marks wrap long attribute lists);
# a Dart raw string is single-line, so every run of whitespace becomes one
# space.
INNER_WS = re.compile(r"\s+")


def clean(svg: str) -> str:
    svg = META.sub("", svg)
    svg = C2PA_NS.sub("", svg)
    svg = WS.sub("><", svg).strip()
    svg = INNER_WS.sub(" ", svg)
    if "\n" in svg or "\r" in svg:
        raise SystemExit("svg still spans lines after cleaning")
    if "viewBox=\"0 0 24 24\"" not in svg:
        raise SystemExit(f"unexpected viewBox: {svg[:80]}")
    if "<script" in svg or "xlink:href" in svg or "<image" in svg:
        raise SystemExit("refusing an svg with script / links / images")
    return svg


def load(folder: str) -> dict:
    out = {}
    for f in sorted(os.listdir(folder)):
        if not f.endswith(".svg"):
            continue
        key = f[:-4].replace("-", "_")
        out[key] = clean(io.open(os.path.join(folder, f), encoding="utf-8").read())
    return out


line = load(os.path.join(HERE, "svg", "line"))
brand = load(os.path.join(HERE, "svg", "brand"))
index = json.load(io.open(os.path.join(HERE, "line-index.json"), encoding="utf-8"))
categories = {e["name"].replace("-", "_"): e["category"] for e in index}
missing = [k for k in line if k not in categories]
if missing:
    raise SystemExit(f"line icons without a category in line-index.json: {missing}")


def dart_string(s: str) -> str:
    # Raw string: the SVGs contain no single quotes or $ signs by construction.
    if "'" in s or "$" in s:
        raise SystemExit("svg contains a quote or dollar; extend the escaper")
    return "r'" + s + "'"


with io.open(OUT, "w", encoding="utf-8", newline="\n") as out:
    out.write("// GENERATED by tool/host_icons/gen_host_icons.py. Do not edit by hand.\n")
    out.write("//\n// The host-card icon set as inline SVG, keyed by catalog id: the generic\n")
    out.write("// line icons (24x24, 1.75 stroke) and the OS / brand marks (Simple Icons\n")
    out.write("// paths, 24x24 with a 2px inset). All are single-colour and tinted at\n")
    out.write("// render time; see OsCatalog for names, categories and colours.\n\n")
    out.write("// ignore_for_file: lines_longer_than_80_chars\n\n")
    out.write("/// Generic line icons by id (`server_rack`, `load_balancer`, ...).\n")
    out.write("const Map<String, String> kHostLineIconSvgs = <String, String>{\n")
    for k, v in line.items():
        out.write(f"  '{k}': {dart_string(v)},\n")
    out.write("};\n\n")
    out.write("/// Line icon id -> catalog category name, from the icon set's own index.\n")
    out.write("const Map<String, String> kHostLineIconCategories = <String, String>{\n")
    for k in line:
        out.write(f"  '{k}': '{categories[k]}',\n")
    out.write("};\n\n")
    out.write("/// OS / brand marks by catalog id.\n")
    out.write("const Map<String, String> kHostBrandIconSvgs = <String, String>{\n")
    for k, v in brand.items():
        out.write(f"  '{k}': {dart_string(v)},\n")
    out.write("};\n")

print(f"wrote {OUT}: {len(line)} line icons, {len(brand)} brand marks")
