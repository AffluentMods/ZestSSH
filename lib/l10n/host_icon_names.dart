/// The name a group's icon (folderIconChoices) is shown by, in the person's
/// language, on hover and to a screen reader: a host icon's name where the two
/// show the same thing (3.0, 17 October 2026: the icons of a group's picker
/// had no names).
String folderIconName(IconData icon, AppLocalizations l10n) {
  String host(String id) => hostIconName(OsCatalog.get(id), l10n);
  final names = <int, String Function()>{
    LucideIcons.folder.codePoint: () => l10n.iconNameFolder,
    LucideIcons.server.codePoint: () => host('server'),
    LucideIcons.database.codePoint: () => host('database'),
    LucideIcons.cloud.codePoint: () => host('cloud'),
    LucideIcons.shield.codePoint: () => host('shield'),
    LucideIcons.home.codePoint: () => host('home'),
    LucideIcons.briefcase.codePoint: () => host('office'),
    LucideIcons.globe.codePoint: () => host('globe'),
    LucideIcons.cpu.codePoint: () => host('cpu'),
    LucideIcons.hardDrive.codePoint: () => host('hard_drive'),
    LucideIcons.network.codePoint: () => host('network'),
    LucideIcons.box.codePoint: () => host('package'),
    LucideIcons.boxes.codePoint: () => l10n.iconNameBoxes,
    LucideIcons.layers.codePoint: () => l10n.iconNameLayers,
    LucideIcons.flaskConical.codePoint: () => host('staging'),
    LucideIcons.gamepad2.codePoint: () => host('game_controller'),
    LucideIcons.terminal.codePoint: () => host('shell'),
    LucideIcons.monitor.codePoint: () => host('desktop'),
    LucideIcons.container.codePoint: () => host('containers'),
    LucideIcons.rocket.codePoint: () => host('production'),
    LucideIcons.users.codePoint: () => host('users'),
    LucideIcons.code2.codePoint: () => host('code'),
    LucideIcons.building.codePoint: () => host('datacenter'),
    LucideIcons.lock.codePoint: () => host('lock'),
  };
  return (names[icon.codePoint] ?? () => l10n.iconNameFolder)();
}
