import 'dart:convert';
import 'dart:typed_data';

import 'package:crypto/crypto.dart' as crypto;

import 'ssh_wire.dart';

/// All five user-cert algorithm identifiers OpenSSH defines.
///
/// Constants in lower-case match the on-the-wire string exactly. Lookups
/// elsewhere should always go through [SshCertAlgorithm.fromName] so
/// surrounding whitespace / casing variations don't slip through.
enum SshCertAlgorithm {
  rsaSha2_256('rsa-sha2-256-cert-v01@openssh.com', 'ssh-rsa'),
  rsaSha2_512('rsa-sha2-512-cert-v01@openssh.com', 'ssh-rsa'),
  rsaSha1('ssh-rsa-cert-v01@openssh.com', 'ssh-rsa'),
  ecdsaP256('ecdsa-sha2-nistp256-cert-v01@openssh.com',
      'ecdsa-sha2-nistp256'),
  ecdsaP384('ecdsa-sha2-nistp384-cert-v01@openssh.com',
      'ecdsa-sha2-nistp384'),
  ecdsaP521('ecdsa-sha2-nistp521-cert-v01@openssh.com',
      'ecdsa-sha2-nistp521'),
  ed25519('ssh-ed25519-cert-v01@openssh.com', 'ssh-ed25519'),
  skEd25519('sk-ssh-ed25519-cert-v01@openssh.com',
      'sk-ssh-ed25519@openssh.com'),
  skEcdsaP256('sk-ecdsa-sha2-nistp256-cert-v01@openssh.com',
      'sk-ecdsa-sha2-nistp256@openssh.com');

  const SshCertAlgorithm(this.name, this.bareKeyName);

  /// On-the-wire algorithm name as it appears in the cert blob and in
  /// the SSH userauth `MSG_USERAUTH_REQUEST`.
  final String name;

  /// The bare-key algorithm name the cert wraps. E.g. an
  /// `ed25519-cert-v01` certificate carries an `ssh-ed25519` key.
  /// Used to verify the underlying private key matches.
  final String bareKeyName;

  static SshCertAlgorithm? fromName(String s) {
    final norm = s.trim();
    for (final v in SshCertAlgorithm.values) {
      if (v.name == norm) return v;
    }
    return null;
  }

  /// The certificate algorithm to issue for a subject key, from its bare
  /// algorithm name. An RSA key gets `ssh-rsa-cert-v01@openssh.com`, the
  /// name `ssh-keygen` writes into every RSA certificate: the
  /// `rsa-sha2-*-cert-v01` names only say which hash signs a login, so
  /// they belong in the userauth request (see SshCertificateKeyPair.type),
  /// not in the certificate, and servers other than OpenSSH refuse them
  /// there. It does not make anything SHA-1: the CA signature and the
  /// login signature each carry their own algorithm.
  static SshCertAlgorithm? forSubjectKey(String bareAlgo) {
    if (bareAlgo == 'ssh-rsa') return SshCertAlgorithm.rsaSha1;
    for (final v in SshCertAlgorithm.values) {
      if (v.bareKeyName == bareAlgo) return v;
    }
    return null;
  }
}

/// Cert type field. OpenSSH defines:
///   1 = SSH2_CERT_TYPE_USER  (cert authorises a user login)
///   2 = SSH2_CERT_TYPE_HOST  (cert authorises a host)
///
/// We only generate user certs but parse both - a user pasting a host
/// cert by mistake should get a clear error, not a cryptic decode
/// failure.
enum SshCertType {
  user(1),
  host(2);

  const SshCertType(this.wire);
  final int wire;

  static SshCertType? fromWire(int v) {
    switch (v) {
      case 1:
        return SshCertType.user;
      case 2:
        return SshCertType.host;
      default:
        return null;
    }
  }
}

/// Parsed OpenSSH SSH user/host certificate.
///
/// Fields mirror PROTOCOL.certkeys (in the OpenSSH source tree).
/// Construction goes through [SshCertificate.parse] / [parseFromOpenSSH]
/// so callers always go through validated decoding.
class SshCertificate {
  SshCertificate({
    required this.algorithm,
    required this.nonce,
    required this.keyAlgorithm,
    required this.keyParts,
    required this.serial,
    required this.type,
    required this.keyId,
    required this.principals,
    required this.validAfter,
    required this.validBefore,
    required this.criticalOptions,
    required this.extensions,
    required this.reserved,
    required this.signatureKey,
    required this.signature,
    required this.toBeSigned,
    required this.fullBlob,
  });

  /// Cert algorithm - wire name + bare-key kind.
  final SshCertAlgorithm algorithm;

  /// 32 random bytes generated by the CA at signing time. Required for
  /// signature verification.
  final Uint8List nonce;

  /// The bare-key algorithm name (e.g. `ssh-ed25519`).
  final String keyAlgorithm;

  /// The raw key material: ed25519 public bytes / RSA (e,n) / ECDSA Q+
  /// curve / FIDO2 sk- (key + application + flags). Stored as the
  /// pre-encoded SSH wire bytes so we can round-trip without re-
  /// encoding each variant. The cert's full public-key blob (the
  /// algorithm-specific portion) is reconstructable as
  /// `wire(algorithm.name) || nonce || keyParts`.
  final Uint8List keyParts;

  /// Monotonic serial number assigned by the CA. Hex-displayed in UI.
  final int serial;

  final SshCertType type;

  /// Free-form CA-assigned identifier. Often a username or audit tag.
  final String keyId;

  /// Allowed remote principals. For user certs these are usernames the
  /// cert is permitted to authenticate as. Empty list = "any".
  final List<String> principals;

  /// Issue time (unix seconds). The CA's clock at signing.
  final int validAfter;

  /// Expiry (unix seconds). The constant `0xFFFFFFFFFFFFFFFF` means
  /// "never expires"; we expose this as `null` via [validBeforeOrNull].
  final int validBefore;

  /// Critical-option key/value list. Unknown options force the server
  /// to reject the cert (per the spec).
  final Map<String, Uint8List> criticalOptions;

  /// Extension key/value list. Unknown extensions are ignored.
  final Map<String, Uint8List> extensions;

  /// Reserved field - always empty in current spec. Preserved for
  /// round-trip integrity.
  final Uint8List reserved;

  /// The CA's public key blob (`signature key` field). Same wire form
  /// as any other SSH public key.
  final Uint8List signatureKey;

  /// The CA's signature over [toBeSigned].
  final Uint8List signature;

  /// Bytes that were signed by the CA. Equal to the cert blob with
  /// [signature] field stripped (everything before the final
  /// length-prefixed signature). Needed for verification.
  final Uint8List toBeSigned;

  /// Complete cert blob, including signature. Used when serialising the
  /// cert as part of a userauth `MSG_USERAUTH_REQUEST`.
  final Uint8List fullBlob;

  // ── Convenience accessors ────────────────────────────────────────

  /// Validity end as a [DateTime], or null when the cert never expires
  /// (OpenSSH "infinite" value 0xFFFFFFFFFFFFFFFF).
  DateTime? get validBeforeOrNull {
    if (validBefore == -1 || validBefore == 0x7FFFFFFFFFFFFFFF) return null;
    // OpenSSH treats 0xFFFFFFFFFFFFFFFF as infinite; on Dart's signed
    // 64-bit int that decodes to -1.
    return DateTime.fromMillisecondsSinceEpoch(validBefore * 1000,
        isUtc: true);
  }

  /// Validity start as a [DateTime].
  DateTime get validAfterDateTime =>
      DateTime.fromMillisecondsSinceEpoch(validAfter * 1000, isUtc: true);

  /// True when [now] is within `[validAfter, validBefore]`.
  bool isValidAt(DateTime now) {
    final secs = now.toUtc().millisecondsSinceEpoch ~/ 1000;
    if (secs < validAfter) return false;
    final exp = validBeforeOrNull;
    if (exp != null && secs >= validBefore) return false;
    return true;
  }

  /// SHA-256 fingerprint of the CA public key (`SHA256:base64-no-pad`),
  /// matching the format printed by `ssh-keygen -lf cert.pub`.
  String get caFingerprint {
    final hash = crypto.sha256.convert(signatureKey).bytes;
    return 'SHA256:${base64.encode(hash).replaceAll('=', '')}';
  }

  /// Comma-separated principals for compact display. Empty list →
  /// "(any)".
  String get principalsLabel =>
      principals.isEmpty ? '(any)' : principals.join(',');

  /// Hex serial - matches the formatting `ssh-keygen -L` uses.
  String get serialHex => serial.toRadixString(16).toUpperCase();

  // ── Parsing ─────────────────────────────────────────────────────

  /// Parse an OpenSSH `<algo> <base64>` line, the same format used in
  /// `~/.ssh/id_*-cert.pub`. Whitespace-separated comment is ignored.
  static SshCertificate parseFromOpenSSH(String line) {
    final trimmed = line.trim();
    if (trimmed.isEmpty) {
      throw const FormatException('SSH cert: empty input');
    }
    final parts = trimmed.split(RegExp(r'\s+'));
    if (parts.length < 2) {
      throw const FormatException(
          'SSH cert: expected `<algo> <base64> [comment]`');
    }
    final algo = SshCertAlgorithm.fromName(parts[0]);
    if (algo == null) {
      throw FormatException(
          'SSH cert: unknown algorithm "${parts[0]}". Expected one of '
          '${SshCertAlgorithm.values.map((a) => a.name).join(", ")}.');
    }
    final Uint8List blob;
    try {
      blob = base64.decode(parts[1]);
    } on FormatException catch (e) {
      throw FormatException('SSH cert: invalid base64 (${e.message})');
    }
    final cert = parse(blob);
    if (cert.algorithm != algo) {
      throw FormatException(
          'SSH cert: header algorithm "${algo.name}" does not match '
          'cert body algorithm "${cert.algorithm.name}". Refusing to '
          'load - either the file is corrupt or someone tampered with '
          'the wrapper.');
    }
    return cert;
  }

  /// Parse a raw SSH cert blob (as it appears on the wire).
  ///
  /// Performs full structural validation. Does NOT verify the CA
  /// signature - that's done by [SshCertVerifier] which knows about
  /// pointycastle. Keeping that out of the parser lets us unit-test
  /// the wire format without dragging in big crypto deps.
  static SshCertificate parse(Uint8List blob) {
    final reader = SshWireReader(blob);

    // 1. algorithm name (string)
    final algoName = reader.readUtf8String(maxLength: 256);
    final algo = SshCertAlgorithm.fromName(algoName);
    if (algo == null) {
      throw FormatException(
          'SSH cert: unknown algorithm "$algoName"');
    }

    // 2. nonce - OpenSSH's PROTOCOL.certkeys says "nonce is a CA-
    // provided random bitstring of arbitrary length that makes
    // attacks that depend on inducing collisions in the signature
    // hash infeasible". `ssh-keygen` always writes exactly 32 bytes;
    // accepting anything else is a downgrade vector. We tolerate 16
    // (legacy implementations) but cap at 64 to prevent unbounded
    // allocations on a malformed blob.
    final nonce = reader.readString(maxLength: 64);
    if (nonce.length < 16) {
      throw FormatException(
          'SSH cert: nonce too short (${nonce.length} bytes; '
          'expected ≥ 16 - possible attempt to weaken signature '
          'binding)');
    }

    // 3. algorithm-specific public key parts. We capture the slice
    // between the nonce end and the serial start so callers can
    // reconstruct the underlying public key blob without knowing the
    // algorithm-specific layout.
    final keyPartsStart = reader.position;
    _skipKeyParts(reader, algo);
    final keyPartsEnd = reader.position;
    final keyParts = Uint8List.sublistView(blob, keyPartsStart, keyPartsEnd);

    // 4. serial (uint64)
    final serial = reader.readUint64();

    // 5. type (uint32) - 1 = user, 2 = host.
    final typeWire = reader.readUint32();
    final type = SshCertType.fromWire(typeWire);
    if (type == null) {
      throw FormatException('SSH cert: unknown cert type $typeWire '
          '(expected 1=user or 2=host)');
    }

    // 6. key id (string)
    final keyId = reader.readUtf8String(maxLength: 4096);

    // 7. valid principals (string of strings)
    final principalsBlob = reader.readSubReader();
    final principals = <String>[];
    while (!principalsBlob.isExhausted) {
      principals.add(principalsBlob.readUtf8String(maxLength: 256));
    }

    // 8. valid after (uint64)
    final validAfter = reader.readUint64();

    // 9. valid before (uint64)
    final validBefore = reader.readUint64();

    // 10. critical options (string of name/data pairs)
    final critical = _readOptionList(reader);

    // 11. extensions
    final extensions = _readOptionList(reader);

    // 12. reserved (string)
    final reserved = reader.readString(maxLength: 1024);

    // 13. signature key (string - CA public key blob)
    final signatureKey = reader.readString(maxLength: 8 * 1024);

    // Capture the to-be-signed prefix BEFORE consuming the signature.
    final toBeSigned = reader.bytesUpToHere();

    // 14. signature (string)
    final signature = reader.readString(maxLength: 4 * 1024);

    if (!reader.isExhausted) {
      throw FormatException('SSH cert: ${reader.remaining} trailing bytes '
          'after signature - the cert blob is corrupt or carries data we '
          'don\'t know how to validate.');
    }

    return SshCertificate(
      algorithm: algo,
      nonce: nonce,
      keyAlgorithm: algo.bareKeyName,
      keyParts: keyParts,
      serial: serial,
      type: type,
      keyId: keyId,
      principals: List.unmodifiable(principals),
      validAfter: validAfter,
      validBefore: validBefore,
      criticalOptions: Map.unmodifiable(critical),
      extensions: Map.unmodifiable(extensions),
      reserved: reserved,
      signatureKey: signatureKey,
      signature: signature,
      toBeSigned: toBeSigned,
      fullBlob: Uint8List.fromList(blob),
    );
  }

  // ── Internal helpers ────────────────────────────────────────────

  /// Walk past the algorithm-specific public-key parts so the parser
  /// can resume at the serial number.
  static void _skipKeyParts(SshWireReader reader, SshCertAlgorithm algo) {
    switch (algo) {
      case SshCertAlgorithm.ed25519:
        // Ed25519: string pk (32 bytes).
        reader.readString(maxLength: 64);
      case SshCertAlgorithm.rsaSha1:
      case SshCertAlgorithm.rsaSha2_256:
      case SshCertAlgorithm.rsaSha2_512:
        // RSA: mpint e, mpint n.
        reader.readMpint();
        reader.readMpint();
      case SshCertAlgorithm.ecdsaP256:
      case SshCertAlgorithm.ecdsaP384:
      case SshCertAlgorithm.ecdsaP521:
        // ECDSA: string curve_name, string Q.
        reader.readString(maxLength: 32);
        reader.readString(maxLength: 256);
      case SshCertAlgorithm.skEd25519:
        // sk-ed25519: string pk, string application.
        reader.readString(maxLength: 64);
        reader.readString(maxLength: 256);
      case SshCertAlgorithm.skEcdsaP256:
        // sk-ecdsa-p256: string curve_name, string Q, string application.
        reader.readString(maxLength: 32);
        reader.readString(maxLength: 256);
        reader.readString(maxLength: 256);
    }
  }

  /// Decode an SSH critical-options / extensions list. Each entry is:
  ///   string name
  ///   string data
  /// Wrapped in an outer length-prefixed string.
  static Map<String, Uint8List> _readOptionList(SshWireReader reader) {
    final inner = reader.readSubReader();
    final out = <String, Uint8List>{};
    while (!inner.isExhausted) {
      final name = inner.readUtf8String(maxLength: 256);
      final data = inner.readString(maxLength: 64 * 1024);
      out[name] = data;
    }
    return out;
  }
}
