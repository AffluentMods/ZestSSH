  0x87: 0x73, 0x88: 0x70, 0x89: 0x7d, 0x8a: 0x79, 0x8b: 0x7b, // Ro, Katakana/Hiragana, Yen, Henkan, Muhenkan
  0xe0: 0x1d, 0xe1: 0x2a, 0xe2: 0x38, 0xe3: 0xdb, // left Ctrl, Shift, Alt, Meta
