/// The key's scancode (QEMU's numbering), or 0 when it has none here.
int scancodeFor(PhysicalKeyboardKey key) {
  final usage = key.usbHidUsage;
  if (usage >> 16 != 0x07) return 0;
  return _hidToXt[usage & 0xffff] ?? 0;
}

/// The key a character is on (a US layout), and whether it needs Shift; null for a character no
/// US key types.
(PhysicalKeyboardKey, bool)? usKey(int ch) {
  const shifted = {
    0x21: 0x1e, 0x40: 0x1f, 0x23: 0x20, 0x24: 0x21, 0x25: 0x22, 0x5e: 0x23, 0x26: 0x24, 0x2a: 0x25, // ! to *
    0x28: 0x26, 0x29: 0x27, 0x5f: 0x2d, 0x2b: 0x2e, 0x7b: 0x2f, 0x7d: 0x30, 0x7c: 0x31, 0x3a: 0x33, // ( to :
    0x22: 0x34, 0x7e: 0x35, 0x3c: 0x36, 0x3e: 0x37, 0x3f: 0x38, // " ~ < > ?
  };
  const plain = {
    0x20: 0x2c, 0x2d: 0x2d, 0x3d: 0x2e, 0x5b: 0x2f, 0x5d: 0x30, 0x5c: 0x31, 0x3b: 0x33, 0x27: 0x34, // space to '
    0x60: 0x35, 0x2c: 0x36, 0x2e: 0x37, 0x2f: 0x38, 0x30: 0x27, // ` , . / 0
  };
  PhysicalKeyboardKey k(int usage) => PhysicalKeyboardKey(0x00070000 | usage);
  if (ch >= 0x61 && ch <= 0x7a) return (k(0x04 + ch - 0x61), false);
  if (ch >= 0x41 && ch <= 0x5a) return (k(0x04 + ch - 0x41), true);
  if (ch >= 0x31 && ch <= 0x39) return (k(0x1e + ch - 0x31), false);
  if (plain[ch] != null) return (k(plain[ch]!), false);
  if (shifted[ch] != null) return (k(shifted[ch]!), true);
  return null;
}

/// The keysym of a character (Latin-1 as is, the rest as 0x01000000 + code point).
int keysymForChar(int ch) => (ch >= 0x20 && ch <= 0x7e) || (ch >= 0xa0 && ch <= 0xff) ? ch : 0x01000000 | ch;
