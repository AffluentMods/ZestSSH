/// The keysym for a key, or null for one we do not send.
int? keysymFor(LogicalKeyboardKey key, String? character) {
  final named = _named[key];
  if (named != null) return named;
  if (character != null && character.runes.length == 1) {
    final c = character.runes.first;
    if ((c >= 0x20 && c <= 0x7e) || (c >= 0xa0 && c <= 0xff)) return c;
    if (c > 0xff) return 0x01000000 | c;
  }
  // Ctrl+letter comes with a control character or none: the key's own letter.
  final id = key.keyId;
  if (id >= 0x20 && id <= 0x7e) return id;
  return null;
}

// USB HID keyboard usages (page 7, what Flutter's PhysicalKeyboardKey.usbHidUsage carries) to
