  0x1c: 0x15, 0x1d: 0x2c, // y, z
  0x1e: 0x02, 0x1f: 0x03, 0x20: 0x04, 0x21: 0x05, 0x22: 0x06, 0x23: 0x07, 0x24: 0x08, 0x25: 0x09, // 1 to 8
  0x26: 0x0a, 0x27: 0x0b, // 9, 0
